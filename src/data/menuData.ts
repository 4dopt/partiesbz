export const MAX_VENUE_CAPACITY = 120;

export function findVenueHall(areaName: string): VenueHall | undefined {
  const normalized = areaName.trim().toLowerCase();
  if (!normalized) return undefined;
  return VENUE_HALLS.find(
    (h) =>
      h.name.toLowerCase() === normalized ||
      (h.id === 'anthem-bar' && normalized === 'anthem') ||
      (h.id === 'fairway-hall' && normalized === 'fairway') ||
      (h.id === 'bunker-bar-hall' && normalized.includes('bunker'))
  );
}

export function getRecommendedHall(totalGuests: number): VenueHall {
  if (totalGuests <= 55) return VENUE_HALLS[0]; // Fairway Hall (recommended 50-55, max 60)
  if (totalGuests <= 80) return VENUE_HALLS[1]; // Anthem Bar (70-80)
  return VENUE_HALLS[2]; // Bunker Bar Hall (recommended 100, max 120)
}

